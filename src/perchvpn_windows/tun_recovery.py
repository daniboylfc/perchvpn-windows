logger = logging.getLogger("perchvpn_windows.tun_recovery")

RECOVERY_UNVERIFIED = "RECOVERY_UNVERIFIED"
CLEAN = "clean"

# sing-box creates the Wintun adapter with the configured interface_name.
# The GUID is generated by Windows, so name-only matching is the effective
# probe unless the journal captured a GUID from a previous activation.
DEFAULT_ADAPTER_GUID = None
DEFAULT_ADAPTER_NAME = "PerchVPN"

_RECORD_VERSION = 2  # v2 adds "network_baseline" for DNS/route-metric restoration
_VERIFY_WINDOW_SECONDS = 8.0
# A row that is provably ours and Down cannot carry traffic; waiting out the
# whole verification window for it to disappear only delays Disconnect (live
# 2026-11-24 run: 8.0 s of the 9.44 s teardown).  Once the baseline restore
# has finished, a down row is released this much later, which still gives a
# promptly-removed row the tidy "record cleared" path.
_DOWN_ROW_RELEASE_GRACE_SECONDS = 0.75
_POLL_INTERVAL_SECONDS = 0.1
_CREATE_TIME_TOLERANCE_SECONDS = 0.05

_VIRTUAL_ADAPTER_MARKERS = (
    "vethernet",
    "hyper-v",
    "wsl",
    "tailscale",
    "vmware",
    "virtualbox",
    "docker",
)


def _is_virtual_adapter(adapter: object) -> bool:
    if not isinstance(adapter, dict):
        return False
    haystack = " ".join(
        str(adapter.get(key) or "") for key in ("Name", "InterfaceDescription")
    ).lower()
    return any(marker in haystack for marker in _VIRTUAL_ADAPTER_MARKERS)


def _adapter_indexes(snapshot: NetworkSnapshot) -> dict:
    indexes = {}
    for adapter in snapshot.adapters:
        if not isinstance(adapter, dict):
            continue
        try:
            indexes[int(adapter.get("InterfaceIndex"))] = adapter
        except (TypeError, ValueError):
            continue
    return indexes


def _difference_interface_index(diff: StateDifference) -> Optional[int]:
    value = (
        diff.current_value
        if isinstance(diff.current_value, dict)
        else diff.baseline_value
    )
    if not isinstance(value, dict):
        return None
    try:
        return int(value.get("InterfaceIndex"))
    except (TypeError, ValueError):
        return None


class RecoveryUnverified(Exception):
    """Raised when the TUN recovery state cannot be proven clean."""


@dataclass
class RecoveryRun:
    """In-memory handle for one gated sidecar run."""

    record: Optional[dict]
    enabled: bool = True


def _default_clock() -> float:
    return time.monotonic()


async def _default_sleep(seconds: float) -> None:
    import asyncio

    await asyncio.sleep(seconds)


def _default_identity(path: str) -> dict:
    stat = os.stat(path)
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return {
        "path": os.path.abspath(path),
        "size": int(stat.st_size),
        "mtime_ns": int(stat.st_mtime_ns),
        "sha256": digest.hexdigest(),
    }


def _windows_creation_time(pid: int) -> Optional[float]:
    import ctypes
    import ctypes.wintypes

    PROCESS_QUERY_LIMITED_INFORMATION = 0x1000
    ERROR_INVALID_PARAMETER = 87

    kernel32 = ctypes.WinDLL("kernel32", use_last_error=True)
    kernel32.OpenProcess.argtypes = [
        ctypes.wintypes.DWORD,
        ctypes.wintypes.BOOL,
        ctypes.wintypes.DWORD,
    ]
    kernel32.OpenProcess.restype = ctypes.wintypes.HANDLE
    kernel32.GetProcessTimes.argtypes = [
        ctypes.wintypes.HANDLE,
        ctypes.POINTER(ctypes.wintypes.FILETIME),
        ctypes.POINTER(ctypes.wintypes.FILETIME),
        ctypes.POINTER(ctypes.wintypes.FILETIME),
        ctypes.POINTER(ctypes.wintypes.FILETIME),
    ]
    kernel32.GetProcessTimes.restype = ctypes.wintypes.BOOL
    kernel32.CloseHandle.argtypes = [ctypes.wintypes.HANDLE]
    kernel32.CloseHandle.restype = ctypes.wintypes.BOOL

    handle = kernel32.OpenProcess(PROCESS_QUERY_LIMITED_INFORMATION, False, int(pid))
    if not handle:
        error = ctypes.get_last_error()
        if error == ERROR_INVALID_PARAMETER:
            return None
        raise RecoveryUnverified(
            "cannot query process %d creation time (error %d)" % (pid, error)
        )
    try:
        creation = ctypes.wintypes.FILETIME()
        exit_time = ctypes.wintypes.FILETIME()
        kernel_time = ctypes.wintypes.FILETIME()
        user_time = ctypes.wintypes.FILETIME()
        ok = kernel32.GetProcessTimes(
            handle,
            ctypes.byref(creation),
            ctypes.byref(exit_time),
            ctypes.byref(kernel_time),
            ctypes.byref(user_time),
        )
        if not ok:
            error = ctypes.get_last_error()
            raise RecoveryUnverified(
                "cannot read process %d creation time (error %d)" % (pid, error)
            )
        ticks = (creation.dwHighDateTime << 32) | creation.dwLowDateTime
        return ticks / 10_000_000.0 - 11_644_473_600.0
    finally:
        kernel32.CloseHandle(handle)


def _boot_time() -> Optional[float]:
    try:
        for line in Path("/proc/stat").read_text().splitlines():
            if line.startswith("btime "):
                return float(line.split()[1])
    except (OSError, ValueError, IndexError):
        return None
    return None


def _posix_creation_time(pid: int) -> Optional[float]:
    stat_path = Path("/proc") / str(pid) / "stat"
    try:
        text = stat_path.read_text()
    except FileNotFoundError:
        return None
    except PermissionError as exc:
        raise RecoveryUnverified("cannot read process %d stat" % pid) from exc
    except OSError:
        return None

    rparen = text.rfind(")")
    if rparen == -1:
        raise RecoveryUnverified("cannot parse process %d stat" % pid)
    fields = text[rparen + 2:].split()
    try:
        start_ticks = int(fields[19])
    except (IndexError, ValueError) as exc:
        raise RecoveryUnverified("cannot parse process %d start time" % pid) from exc
    btime = _boot_time()
    if btime is None:
        raise RecoveryUnverified("cannot read system boot time")
    try:
        ticks_per_second = os.sysconf("SC_CLK_TCK")
    except (ValueError, OSError) as exc:
        raise RecoveryUnverified("cannot read system clock ticks") from exc
    return btime + (start_ticks / ticks_per_second)


def _default_creation_time(pid: int) -> Optional[float]:
    if sys.platform == "win32":
        return _windows_creation_time(pid)
    if sys.platform.startswith("linux"):
        return _posix_creation_time(pid)
    raise RecoveryUnverified("process creation time is not supported on this platform")


def _ps_quote(value: str) -> str:
    return "'" + str(value).replace("'", "''") + "'"


def _default_adapter_probe(
    guid: Optional[str], name: str, *, require_up: bool = False
) -> Optional[bool]:
    try:
        from perchvpn_windows import iphelper

        if iphelper.available():
            native = iphelper.adapter_present_native(guid, name, require_up=require_up)
            if native is not None:
                return native
    except Exception:
        pass
    if sys.platform != "win32":
        return None
    return _powershell_adapter_probe(guid, name)


def _without_transient_trial_adapter(
    diffs: List[StateDifference], adapter_name: str
) -> List[StateDifference]:
    """Drop the trial adapter's own "added" row from a rollback plan.

    sing-box creates the Wintun adapter and removes it on exit, so the
    recovery gate must never disable it.  Wintun can keep listing the device
    for a few hundred ms after the sidecar terminates, which made the
    rollback validator refuse the whole restoration and latch a clean
    teardown as RECOVERY_UNVERIFIED.
    """
    kept: List[StateDifference] = []
    for diff in diffs:
        if diff.category == "adapter" and "added" in str(diff.description or ""):
            current = diff.current_value or {}
            if str(current.get("Name", "")) == adapter_name:
                logger.debug(
                    "ignoring trial adapter still listed during rollback: %s",
                    diff.description,
                )
                continue
        kept.append(diff)
    return kept


def _accepts_require_up(probe: Callable[..., Optional[bool]]) -> bool:
    try:
        return "require_up" in inspect.signature(probe).parameters
    except (TypeError, ValueError):
        return False


def _powershell_adapter_probe(guid: Optional[str], name: str) -> Optional[bool]:
    if guid is None:
        script = (
            "$ErrorActionPreference='Stop';"
            "$n=%s;"
            "try {"
            "  $a = Get-NetAdapter -IncludeHidden -ErrorAction Stop | Where-Object {"
            "    ($null -ne $_.Name -and $_.Name -eq $n)"
            "  };"
            "  if ($a) { exit 1 } else { exit 0 }"
            "} catch { exit 2 }"
        ) % (_ps_quote(name),)
    else:
        script = (
            "$ErrorActionPreference='Stop';"
            "$g=%s; $n=%s;"
            "try {"
            "  $a = Get-NetAdapter -IncludeHidden -ErrorAction Stop | Where-Object {"
            "    ($null -ne $_.InterfaceGuid -and ($_.InterfaceGuid -replace '[{}]','') -eq $g) -or"
            "    ($null -ne $_.Name -and $_.Name -eq $n)"
            "  };"
            "  if ($a) { exit 1 } else { exit 0 }"
            "} catch { exit 2 }"
        ) % (_ps_quote(guid), _ps_quote(name))

    try:
        completed = run_hidden(
            powershell_argv(script, executable="powershell"),
            capture_output=True,
            timeout=3.0,
            check=False,
        )
    except (OSError, subprocess.TimeoutExpired):
        return None
    if completed.returncode == 0:
        return False
    if completed.returncode == 1:
        return True
    return None


class TunRecoveryGate:
    """Persist and verify ownership of the TUN sidecar's Wintun adapter."""

    def __init__(
        self,
        *,
        enabled: Optional[bool] = None,
        state_path: Optional[Path] = None,
        adapter_guid: Optional[str] = DEFAULT_ADAPTER_GUID,
        adapter_name: str = DEFAULT_ADAPTER_NAME,
        adapter_probe: Optional[Callable[[str, str], Optional[bool]]] = None,
        creation_time_probe: Optional[Callable[[int], Optional[float]]] = None,
        identity_probe: Optional[Callable[[str], dict]] = None,
        snapshot_capture: Optional[Callable[[], NetworkSnapshot]] = None,
        rollback_executor: Optional[Callable[[str], str]] = None,
        clock: Optional[Callable[[], float]] = None,
        sleep: Optional[Callable[[float], Awaitable[None]]] = None,
        window_seconds: float = _VERIFY_WINDOW_SECONDS,
    ) -> None:
        self.enabled = (sys.platform == "win32") if enabled is None else bool(enabled)
        self.state_path = (
            Path(state_path) if state_path is not None else get_tun_ownership_path()
        )
        self.adapter_guid = adapter_guid if adapter_guid is None else str(adapter_guid)
        self.adapter_name = str(adapter_name)
        self._adapter_probe = adapter_probe or _default_adapter_probe
        self._adapter_probe_require_up = _accepts_require_up(self._adapter_probe)
        self._creation_time_probe = creation_time_probe or _default_creation_time
        self._identity_probe = identity_probe or _default_identity
        # Verification snapshots go through the native IP Helper capture
        # first (milliseconds, no process spawn); PowerShell batched/pool
        # capture remains as the fallback.  The 2026-11-14 01:52 run measured
        # the batched path at ~12 s wall on cold CIM and the pool at ~3-4 s;
        # native capture removes both from the post-stop verify path.
        self._snapshot_capture = snapshot_capture or capture_snapshot_preferred
        self._rollback_executor = rollback_executor or _run_ps_write
        self._clock = clock or _default_clock
        self._sleep = sleep or _default_sleep
        self._window_seconds = float(window_seconds)

    def creation_time(self, pid: int) -> Optional[float]:
        if not self.enabled:
            return None
        return self._creation_time_probe(int(pid))

    def _is_virtual_adapter_drift(
        self,
        diff: StateDifference,
        *,
        baseline: NetworkSnapshot,
        current: NetworkSnapshot,
        adapter_name: str,
    ) -> bool:
        if diff.category == "adapter":
            adapter = (
                diff.current_value
                if isinstance(diff.current_value, dict)
                else diff.baseline_value
            )
            if not isinstance(adapter, dict):
                return False
            if str(adapter.get("Name") or "") == adapter_name:
                return False
            return _is_virtual_adapter(adapter)
        if diff.category not in ("route", "ip_address", "interface", "dns"):
            return False
        index = _difference_interface_index(diff)
        if index is None:
            return False
        for adapters in (_adapter_indexes(current), _adapter_indexes(baseline)):
            adapter = adapters.get(index)
            if adapter is None:
                continue
            if str(adapter.get("Name") or "") == adapter_name:
                continue
            if _is_virtual_adapter(adapter):
                return True
        return False

    def _filter_virtual_adapter_drift(
        self,
        diffs: list,
        *,
        baseline: NetworkSnapshot,
        current: NetworkSnapshot,
        adapter_name: str,
    ) -> tuple:
        kept = []
        ignored = []
        for diff in diffs:
            if self._is_virtual_adapter_drift(
                diff,
                baseline=baseline,
                current=current,
                adapter_name=adapter_name,
            ):
                ignored.append(diff)
            else:
                kept.append(diff)
        if ignored:
            logger.info(
                "Ignoring virtual adapter drift: %s",
                "; ".join(diff.description for diff in ignored),
            )
        return kept, ignored

    def _reset_unverified_if_clean(
        self,
        record: dict,
        current: NetworkSnapshot,
        adapter_name: str,
    ) -> None:
        if (
            record.get("adapter_guid") != self.adapter_guid
            or record.get("adapter_name") != adapter_name
        ):
            raise RecoveryUnverified(
                "unverified ownership record adapter identity mismatch"
            )
        if self._probe_adapter(adapter_name, require_up=True):
            raise RecoveryUnverified(
                "an adapter from the unverified TUN run survives"
            )
        pid = record.get("pid")
        if pid is not None:
            if not isinstance(pid, int) or pid <= 0:
                raise RecoveryUnverified(
                    "unverified ownership record has an invalid PID"
                )
            create_time = record.get("create_time")
            if isinstance(create_time, (int, float)):
                live = self._creation_time_probe(pid)
                if live is not None and (
                    abs(float(live) - float(create_time))
                    <= _CREATE_TIME_TOLERANCE_SECONDS
                ):
                    raise RecoveryUnverified(
                        "recorded TUN sidecar (PID %d) is still running" % pid
                    )
        try:
            baseline = NetworkSnapshot.from_dict(record["network_baseline"])
        except (CaptureError, ValueError, KeyError) as exc:
            raise RecoveryUnverified(
                "invalid network baseline in unverified ownership record: %s" % exc
            ) from exc
        try:
            diffs = compare_snapshots(baseline, current)
        except CaptureError as exc:
            raise RecoveryUnverified(
                "cannot compare unverified ownership baseline: %s" % exc
            ) from exc
        diffs, _ = self._filter_virtual_adapter_drift(
            diffs,
            baseline=baseline,
            current=current,
            adapter_name=adapter_name,
        )
        owned, _ = partition_diffs(
            diffs,
            adapter_name=adapter_name,
            current_snapshot=current,
            baseline_snapshot=baseline,
        )
        owned = _without_transient_trial_adapter(owned, adapter_name)
        if owned:
            raise RecoveryUnverified(
                "unverified TUN state still has %d owned diff(s); refusing "
                "operator reset (first: %s)"
                % (len(owned), owned[0].description)
            )
        self._clear_record()
        logger.info(
            "cleared stale unverified TUN ownership after clean baseline recapture"
        )

    def pre_start(
        self,
        executable_path: str,
        adapter_name: Optional[str] = None,
        *,
        operator_trial: bool = False,
    ) -> RecoveryRun:
        """Validate prior state and persist a prepared ownership record.

        Raises :class:`RecoveryUnverified` when the state cannot be proven clean.
        An operator-requested trial may clear a stale ``unverified`` latch after
        a clean baseline recapture, but only when no trial-owned drift remains.
        """
        if not self.enabled:
            return RecoveryRun(record=None, enabled=False)

        name = adapter_name or self.adapter_name
        # Identity hashing, the PowerShell baseline capture and the adapter
        # presence probe are independent: run them in one parallel step
        # instead of serializing ~1-2 s of PS spawns behind the capture.
        # The probe is speculative — it is only needed when no ownership
        # record exists, so the record file is peeked (cheap local read)
        # before launching it.
        probe_future = None
        pool = ThreadPoolExecutor(max_workers=3)
        try:
            try:
                existing_peek = self._load_record()
            except Exception:  # noqa: BLE001 - corrupt record: probe anyway
                existing_peek = None
            if existing_peek is None:
                probe_future = pool.submit(self._probe_adapter, name)
            identity_future = pool.submit(self._identity_probe, executable_path)
            capture_future = pool.submit(self._snapshot_capture)
            try:
                identity = identity_future.result()
            except Exception as exc:  # noqa: BLE001
                raise RecoveryUnverified(
                    "cannot verify executable identity: %s" % exc
                ) from exc
            try:
                current = capture_future.result()
            except CaptureError as exc:
                raise RecoveryUnverified(
                    "cannot capture pre-trial network baseline: %s" % exc
                ) from exc
            baseline = current.to_dict()

            with self._locked():
                existing = self._load_record()
                if existing is not None:
                    if probe_future is not None:
                        # Discard the speculative probe; its verdict is not
                        # part of the owned-record path.
                        with contextlib.suppress(Exception):
                            probe_future.result()
                    state = existing.get("state")
                    if state == "released":
                        self._consume_released(existing, name)
                        self._clear_record()
                    elif state == "unverified" and operator_trial:
                        self._reset_unverified_if_clean(existing, current, name)
                    elif state in ("prepared", "unverified"):
                        raise RecoveryUnverified(
                            "previous TUN run left an ambiguous %s ownership record; "
                            "operator action is required" % state
                        )
                    else:
                        self._validate_existing(existing, identity, name)
                        self._clear_record()
                else:
                    try:
                        if probe_future is not None:
                            present = probe_future.result()
                        else:
                            # Record vanished between the peek and the lock;
                            # run the probe now (rare fallback path).
                            present = self._probe_adapter(name)
                    except RecoveryUnverified:
                        raise
                    except Exception as exc:  # noqa: BLE001
                        raise RecoveryUnverified(
                            "adapter probe failed: %s" % exc
                        ) from exc
                    if present:
                        raise RecoveryUnverified(
                            "adapter %r/%s is already present without an ownership record"
                            % (name, self.adapter_guid)
                        )

            record = {
                "version": _RECORD_VERSION,
                "state": "prepared",
                "adapter_guid": self.adapter_guid,
                "adapter_name": name,
                "executable": identity,
                "network_baseline": baseline,
                "pid": None,
                "create_time": None,
                "pre_start_present": False,
                "updated_at": self._clock(),
            }
            self._write_record(record)
            return RecoveryRun(record=record, enabled=True)
        finally:
            pool.shutdown(wait=False)

    def mark_running(
        self, run: RecoveryRun, pid: int, create_time: Optional[float]
    ) -> None:
        """Persist the child PID and creation time after a successful spawn."""
        if not run.enabled:
            return
        if run.record is None:
            raise RecoveryUnverified("ownership record is missing")
        if create_time is None:
            raise RecoveryUnverified("cannot verify child process creation time")

        with self._locked():
            current = self._load_record()
            if current is None:
                raise RecoveryUnverified(
                    "ownership record disappeared before the sidecar started"
                )
            if current.get("state") != "prepared":
                raise RecoveryUnverified(
                    "ownership record is not in the prepared state"
                )
            current["state"] = "running"
            current["pid"] = int(pid)
            current["create_time"] = float(create_time)
            current["updated_at"] = self._clock()
            self._write_record(current)
            run.record = current

    async def verify_after_exit(self, run: RecoveryRun) -> str:
        """Poll for adapter removal and return ``CLEAN`` or ``RECOVERY_UNVERIFIED``.

        The baseline restoration runs concurrently with the adapter-absence
        poll: sing-box is already dead when this runs, so restoring owned
        routes/DNS while the zombie adapter lingers is safe (the restored
        commands only target the physical adapter) and the teardown no
        longer serializes the two waits.
        """
        if not run.enabled:
            return CLEAN
        if run.record is None:
            return RECOVERY_UNVERIFIED

        with self._locked():
            try:
                current = self._load_record()
            except RecoveryUnverified:
                return RECOVERY_UNVERIFIED
            if current is None:
                return RECOVERY_UNVERIFIED
            if not self._record_matches_run(current, run.record):
                return RECOVERY_UNVERIFIED

            name = current["adapter_name"]
            restore_task = asyncio.ensure_future(
                asyncio.to_thread(self._restore_from_baseline, current)
            )
            deadline = self._clock() + self._window_seconds
            down_since: Optional[float] = None
            while True:
                # Two questions per poll: does the row still exist, and is it
                # Up?  A Wintun device that the driver has torn down can sit
                # in the adapter table with IfOperStatus Down for seconds.
                # Deciding "clean" on the Up probe alone (the old behaviour)
                # cleared the ownership record while the row was still there;
                # the next Connect then saw an unowned adapter and failed
                # closed forever ("tunnel failed" after multi-country
                # switches).  A probe that cannot answer is inconclusive, not
                # evidence of survival: keep polling until the deadline.
                try:
                    up = self._probe_adapter(name, require_up=True)
                except Exception:  # noqa: BLE001 - retried until the deadline
                    up = None
                try:
                    present = self._probe_adapter(name)
                except Exception:  # noqa: BLE001 - retried until the deadline
                    present = None
                if present is False:
                    # Restore the baseline BEFORE clearing the record so the
                    # durable ownership record + baseline survive a crash
                    # mid-restoration.
                    try:
                        await restore_task
                    except RecoveryUnverified as exc:
                        logger.error("TUN baseline restoration failed: %s", exc)
                        return self._mark_unverified(current)
                    except Exception as exc:  # noqa: BLE001 - fail closed
                        logger.error("TUN baseline restoration failed: %s", exc)
                        return self._mark_unverified(current)
                    self._clear_record()
                    return CLEAN

                now = self._clock()
                if up is False:
                    if down_since is None:
                        down_since = now
                else:
                    down_since = None
                if (
                    down_since is not None
                    and (now - down_since) >= _DOWN_ROW_RELEASE_GRACE_SECONDS
                    and restore_task.done()
                ):
                    # Same verdict as the deadline branch, decided as soon as
                    # it is provable: a down row plus a finished baseline
                    # restore is a clean teardown.  The released record keeps
                    # the next Connect fail-closed against a live sidecar or
                    # an Up adapter.
                    if self._restore_failed(restore_task):
                        return self._mark_unverified(current)
                    return self._release_down_row(current, name, now - down_since)
                if now >= deadline:
                    await self._settle_restore(restore_task)
                    if self._restore_failed(restore_task):
                        return self._mark_unverified(current)
                    if up is False:
                        # Only a down row remains: it is provably ours and it
                        # cannot carry traffic, so keep a released record for
                        # pre_start() to validate and consume.  A latch here
                        # would need an operator (reboot) for no safety gain.
                        return self._release_down_row(
                            current, name, self._window_seconds
                        )
                    return self._mark_unverified(current)
                await self._sleep(
                    min(_POLL_INTERVAL_SECONDS, max(0.0, deadline - now))
                )

    def _release_down_row(self, current: dict, name: str, waited: float) -> str:
        """Persist the ``released`` ownership record for a lingering down row."""
        released = dict(current)
        released["state"] = "released"
        released["updated_at"] = self._clock()
        try:
            self._write_record(released)
        except Exception:  # noqa: BLE001
            logger.error(
                "could not persist released TUN ownership record",
                exc_info=True,
            )
            return self._mark_unverified(current)
        logger.info(
            "TUN adapter %r is down but still listed after %.1fs; keeping a "
            "released ownership record for the next start",
            name,
            waited,
        )
        return CLEAN

    @staticmethod
    def _restore_failed(restore_task: "asyncio.Future") -> bool:
        if not restore_task.done():
            return False
        if restore_task.cancelled():
            return True
        return restore_task.exception() is not None

    @staticmethod
    async def _settle_restore(restore_task: "asyncio.Future") -> None:
        """Wait out a concurrent restoration on an unverified return path."""
        try:
            await restore_task
        except asyncio.CancelledError:
            raise
        except Exception:
            pass

    def clear_run(self, run: Optional[RecoveryRun]) -> None:
        """Best-effort removal of a prepared record after a failed spawn."""
        if run is None or not run.enabled:
            return
        try:
            with self._locked():
                self._clear_record()
        except Exception:  # noqa: BLE001
            logger.warning("could not clear TUN ownership record", exc_info=True)

    def reconcile_stale_ownership(self) -> str:
        """Cold-start reconciliation of a stale ownership record.

        Called when no in-process recovery run exists (e.g. both the
        controller and the sidecar died together).  A ``running`` or
        ``unverified`` record whose recorded process is dead and whose owned
        adapter is absent is validated against its own persisted baseline:
        trial-owned residual drift (if any) is restored and verified; only
        then is the durable record cleared, returning ``CLEAN``.  A live
        recorded process or a surviving adapter keeps the record.  Every
        failure path keeps the record on disk (upgraded to
        ``state="unverified"``) so future ``pre_start`` calls stay blocked —
        reconciliation is idempotent and never blindly clears.
        """
        if not self.enabled:
            return CLEAN
        with self._locked():
            try:
                record = self._load_record()
            except RecoveryUnverified:
                return RECOVERY_UNVERIFIED
            if record is None:
                return CLEAN
            state = str(record.get("state", ""))
            if state in ("unverified", "released"):
                pid = record.get("pid")
                create_time = record.get("create_time")
                if pid is not None and create_time is not None:
                    try:
                        live = self._creation_time_probe(int(pid))
                    except Exception:  # noqa: BLE001
                        logger.error(
                            "cannot validate recorded PID during ownership "
                            "reconciliation",
                            exc_info=True,
                        )
                        return self._mark_unverified(record)
                    if live is not None and (
                        abs(float(live) - float(create_time))
                        <= _CREATE_TIME_TOLERANCE_SECONDS
                    ):
                        logger.error(
                            "recorded sidecar (PID %s) is still alive; "
                            "refusing to reconcile ownership record", pid,
                        )
                        return self._mark_unverified(record)
            elif state not in ("running", "released"):
                # prepared records are evidence until the gate proves the
                # spawn never happened; keep them.
                return RECOVERY_UNVERIFIED
            name = str(record.get("adapter_name", self.adapter_name))
            try:
                present = self._probe_adapter(name, require_up=True)
            except Exception:  # noqa: BLE001
                logger.error(
                    "adapter probe failed during ownership reconciliation",
                    exc_info=True,
                )
                return self._mark_unverified(record)
            if present is None:
                return self._mark_unverified(record)
            if present:
                # The sidecar (or an equivalent run) may still be alive.
                # Never clear; never delete the adapter.
                logger.error(
                    "owned adapter still present; refusing to reconcile "
                    "ownership record (operator action required)"
                )
                return self._mark_unverified(record)
            try:
                self._restore_from_baseline(record)
            except RecoveryUnverified as exc:
                logger.error(
                    "baseline restoration during ownership reconciliation "
                    "failed: %s", exc,
                )
                return self._mark_unverified(record)
            try:
                self._clear_record()
            except RecoveryUnverified as exc:
                logger.error("could not clear ownership record: %s", exc)
                return RECOVERY_UNVERIFIED
            logger.info("stale ownership record reconciled and cleared")
            return CLEAN

    def _record_matches_run(self, current: dict, expected: dict) -> bool:
        if current.get("adapter_guid") != expected.get("adapter_guid"):
            return False
        if current.get("adapter_name") != expected.get("adapter_name"):
            return False
        if current.get("executable") != expected.get("executable"):
            return False
        if current.get("pid") != expected.get("pid"):
            return False
        current_time = current.get("create_time")
        expected_time = expected.get("create_time")
        if current_time is None or expected_time is None:
            return current_time == expected_time
        return (
            abs(float(current_time) - float(expected_time))
            <= _CREATE_TIME_TOLERANCE_SECONDS
        )

    def _probe_adapter(self, name: str, *, require_up: bool = False) -> bool:
        probe = self._adapter_probe
        try:
            if require_up and self._adapter_probe_require_up:
                present = probe(self.adapter_guid, name, require_up=True)  # type: ignore[call-arg]
            else:
                present = probe(self.adapter_guid, name)
        except RecoveryUnverified:
            raise
        except Exception as exc:  # noqa: BLE001
            raise RecoveryUnverified("adapter probe failed: %s" % exc) from exc
        if present is None:
            raise RecoveryUnverified("adapter probe was inconclusive")
        return bool(present)

    def _consume_released(self, record: dict, name: str) -> None:
        """Validate a released ownership record and allow the next start.

        A released record means the previous run's adapter row outlived the
        sidecar (Windows keeps it listed with IfOperStatus Down).  It is only
        safe to adopt when the identity still matches ours and no live sidecar
        holds it; a released adapter that is *Up* means something is using our
        name, which stays fail-closed.
        """
        if record.get("adapter_guid") != self.adapter_guid:
            raise RecoveryUnverified("released ownership record GUID mismatch")
        if record.get("adapter_name") != name:
            raise RecoveryUnverified("released ownership record adapter name mismatch")
        pid = record.get("pid")
        create_time = record.get("create_time")
        if isinstance(pid, int) and pid > 0 and isinstance(create_time, (int, float)):
            try:
                live = self._creation_time_probe(pid)
            except RecoveryUnverified:
                raise
            except Exception as exc:  # noqa: BLE001
                raise RecoveryUnverified(
                    "cannot validate the released sidecar PID: %s" % exc
                ) from exc
            if live is not None and (
                abs(float(live) - float(create_time))
                <= _CREATE_TIME_TOLERANCE_SECONDS
            ):
                raise RecoveryUnverified(
                    "released TUN sidecar (PID %d) is still running" % pid
                )
        try:
            still_up = self._probe_adapter(name, require_up=True)
        except RecoveryUnverified:
            raise
        except Exception as exc:  # noqa: BLE001
            raise RecoveryUnverified(
                "adapter probe failed for the released record: %s" % exc
            ) from exc
        if still_up:
            raise RecoveryUnverified(
                "adapter %r is up under a released ownership record; refusing "
                "to adopt it" % name
            )
        logger.info(
            "released TUN ownership record validated; the adapter row is down "
            "and the next start may reuse the name"
        )

    def _validate_existing(self, record: dict, identity: dict, name: str) -> None:
        if record.get("adapter_guid") != self.adapter_guid:
            raise RecoveryUnverified("ownership record adapter GUID mismatch")
        if record.get("adapter_name") != name:
            raise RecoveryUnverified("ownership record adapter name mismatch")
        if record.get("executable") != identity:
            raise RecoveryUnverified("ownership record executable identity mismatch")

        pid = record.get("pid")
        if pid is not None:
            if not isinstance(pid, int) or pid <= 0:
                raise RecoveryUnverified("ownership record has an invalid PID")
            create_time = record.get("create_time")
            if not isinstance(create_time, (int, float)):
                raise RecoveryUnverified(
                    "ownership record has no process creation time"
                )
            try:
                live = self._creation_time_probe(pid)
            except RecoveryUnverified:
                raise
            except Exception as exc:  # noqa: BLE001
                raise RecoveryUnverified(
                    "cannot validate recorded PID %d: %s" % (pid, exc)
                ) from exc
            if live is not None and (
                abs(float(live) - float(create_time))
                <= _CREATE_TIME_TOLERANCE_SECONDS
            ):
                raise RecoveryUnverified(
                    "recorded TUN sidecar (PID %d) is still running" % pid
                )

        present = self._probe_adapter(name)
        if present:
            raise RecoveryUnverified(
                "an adapter from a previous TUN run survives"
            )

        # Post-crash: the sidecar is gone and the adapter was removed, so the
        # network state is safe to restore before a new sidecar is spawned.
        self._restore_from_baseline(record)

    def _restore_from_baseline(self, record: dict) -> None:
        """Restore pre-trial DNS/route state from the record's baseline.

        Runs capture -> compare -> remediation -> independent post-restore
        verification.  Raises :class:`RecoveryUnverified` (fail closed) when
        the baseline is unusable, capture fails, a rollback command fails, or
        residual drift remains after the commands ran.
        """
        try:
            baseline = NetworkSnapshot.from_dict(record["network_baseline"])
        except (CaptureError, ValueError, KeyError) as exc:
            raise RecoveryUnverified(
                "invalid network baseline in ownership record: %s" % exc
            ) from exc

        try:
            current = self._snapshot_capture()
        except CaptureError as exc:
            raise RecoveryUnverified(
                "cannot capture state for rollback: %s" % exc
            ) from exc

        name = str(record.get("adapter_name", self.adapter_name))
        try:
            diffs = compare_snapshots(baseline, current)
        except CaptureError as exc:
            raise RecoveryUnverified(
                "cannot compare snapshots for rollback: %s" % exc
            ) from exc
        diffs, _ = self._filter_virtual_adapter_drift(
            diffs,
            baseline=baseline,
            current=current,
            adapter_name=name,
        )

        if not diffs:
            logger.info("Network state matches baseline; nothing to restore")
            return

        owned_diffs, ambient_diffs = partition_diffs(
            diffs,
            adapter_name=name,
            current_snapshot=current,
            baseline_snapshot=baseline,
        )
        if ambient_diffs:
            logger.warning(
                "Ambient (non-trial) drift retained, not remediated: %s",
                "; ".join(
                    "%s: %s" % (d.category, d.description)
                    for d in ambient_diffs
                ),
            )

        owned_diffs = _without_transient_trial_adapter(owned_diffs, name)
        if not owned_diffs:
            logger.info(
                "Only ambient drift detected; owned state matches baseline"
            )
            return

        try:
            commands = generate_rollback_commands(owned_diffs)
        except RollbackError as exc:
            raise RecoveryUnverified(
                "refusing unsafe rollback mutation: %s" % exc
            ) from exc
        except CaptureError as exc:
            raise RecoveryUnverified(
                "cannot compute rollback commands: %s" % exc
            ) from exc

        logger.info(
            "Restoring pre-trial network baseline: %d owned drift item(s), %d command(s), %d ambient item(s) retained",
            len(owned_diffs),
            len(commands),
            len(ambient_diffs),
        )
        for command in commands:
            try:
                self._rollback_executor(command)
            except RollbackError as exc:
                if _is_missing_object_text(str(exc)):
                    logger.info(
                        "Ignoring already-remediated entity during rollback (%r): %s",
                        command,
                        exc,
                    )
                    continue
                raise RecoveryUnverified(
                    "rollback command failed (%r): %s" % (command, exc)
                ) from exc

        try:
            after = self._snapshot_capture()
            remaining = compare_snapshots(baseline, after)
        except CaptureError as exc:
            raise RecoveryUnverified(
                "post-rollback verification capture failed: %s" % exc
            ) from exc
        remaining, _ = self._filter_virtual_adapter_drift(
            remaining,
            baseline=baseline,
            current=after,
            adapter_name=name,
        )
        remaining_owned, remaining_ambient = partition_diffs(
            remaining,
            adapter_name=name,
            current_snapshot=after,
            baseline_snapshot=baseline,
        )
        remaining_owned = _without_transient_trial_adapter(remaining_owned, name)
        if remaining_owned:
            raise RecoveryUnverified(
                "post-rollback verification failed: %d trial-owned diffs remain "
                "(first: %s)" % (
                    len(remaining_owned),
                    remaining_owned[0].description,
                )
            )
        if remaining_ambient:
            logger.warning(
                "Ambient (non-trial) drift remains after restoration: %s",
                "; ".join(
                    "%s: %s" % (d.category, d.description)
                    for d in remaining_ambient
                ),
            )
        logger.info("Pre-trial network baseline verified restored")

    def _mark_unverified(self, record: dict) -> str:
        record["state"] = "unverified"
        record["updated_at"] = self._clock()
        try:
            self._write_record(record)
        except Exception:  # noqa: BLE001
            logger.error(
                "could not persist unverified TUN ownership record", exc_info=True
            )
        return RECOVERY_UNVERIFIED

    def _load_record(self) -> Optional[dict]:
        try:
            raw = self.state_path.read_text(encoding="utf-8")
        except FileNotFoundError:
            return None
        except OSError as exc:
            raise RecoveryUnverified(
                "cannot read TUN ownership record: %s" % exc
            ) from exc

        try:
            record = json.loads(raw)
        except (json.JSONDecodeError, TypeError) as exc:
            raise RecoveryUnverified("TUN ownership record is corrupt") from exc
        if not isinstance(record, dict):
            raise RecoveryUnverified("TUN ownership record is corrupt")
        if record.get("version") != _RECORD_VERSION:
            raise RecoveryUnverified(
                "TUN ownership record version is unsupported (legacy version "
                "1 records cannot be used for network restoration)"
            )
        if record.get("state") not in ("prepared", "running", "unverified", "released"):
            raise RecoveryUnverified("TUN ownership record state is invalid")
        adapter_guid = record.get("adapter_guid")
        if adapter_guid is not None and not isinstance(adapter_guid, str):
            raise RecoveryUnverified(
                "TUN ownership record adapter GUID is invalid"
            )
        if not isinstance(record.get("adapter_name"), str):
            raise RecoveryUnverified(
                "TUN ownership record adapter name is invalid"
            )
        executable = record.get("executable")
        if not isinstance(executable, dict):
            raise RecoveryUnverified(
                "TUN ownership record executable identity is invalid"
            )
        for key in ("path", "size", "mtime_ns", "sha256"):
            if key not in executable:
                raise RecoveryUnverified(
                    "TUN ownership record executable identity is incomplete"
                )
        baseline = record.get("network_baseline")
        if not isinstance(baseline, dict):
            raise RecoveryUnverified(
                "TUN ownership record is missing a valid network baseline"
            )
        try:
            NetworkSnapshot.from_dict(baseline)
        except (CaptureError, ValueError) as exc:
            raise RecoveryUnverified(
                "TUN ownership record has an invalid network baseline: %s" % exc
            ) from exc
        if record.get("state") == "running":
            if not isinstance(record.get("pid"), int) or record["pid"] <= 0:
                raise RecoveryUnverified(
                    "TUN ownership record is missing a valid PID"
                )
            if not isinstance(record.get("create_time"), (int, float)):
                raise RecoveryUnverified(
                    "TUN ownership record is missing a process creation time"
                )
        return record

    def _write_record(self, record: dict) -> None:
        self.state_path.parent.mkdir(parents=True, exist_ok=True)
        fd, tmp_path = tempfile.mkstemp(
            prefix=self.state_path.name + ".tmp-", dir=str(self.state_path.parent)
        )
        try:
            with os.fdopen(fd, "w", encoding="utf-8") as handle:
                json.dump(record, handle, indent=2, sort_keys=True)
                handle.flush()
                os.fsync(handle.fileno())
            os.replace(tmp_path, self.state_path)
        except Exception as exc:  # noqa: BLE001
            raise RecoveryUnverified(
                "cannot persist TUN ownership record: %s" % exc
            ) from exc
        finally:
            if os.path.exists(tmp_path):
                try:
                    os.remove(tmp_path)
                except OSError:
                    pass

    def _clear_record(self) -> None:
        try:
            self.state_path.unlink()
        except FileNotFoundError:
            pass
        except OSError as exc:
            raise RecoveryUnverified(
                "cannot remove TUN ownership record: %s" % exc
            ) from exc

    @contextmanager
    def _locked(self):
        lock_path = self.state_path.with_name(self.state_path.name + ".lock")
        lock_path.parent.mkdir(parents=True, exist_ok=True)
        fd = os.open(str(lock_path), os.O_CREAT | os.O_RDWR, 0o600)
        try:
            if sys.platform == "win32":
                import msvcrt

                os.lseek(fd, 0, os.SEEK_SET)
                msvcrt.locking(fd, msvcrt.LK_NBLCK, 1)
            else:
                import fcntl

                fcntl.flock(fd, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except OSError as exc:
            os.close(fd)
            raise RecoveryUnverified(
                "another TUN recovery operation is in progress"
            ) from exc

        try:
            yield
        finally:
            try:
                if sys.platform == "win32":
                    import msvcrt

                    os.lseek(fd, 0, os.SEEK_SET)
                    msvcrt.locking(fd, msvcrt.LK_UNLCK, 1)
                else:
                    import fcntl

                    fcntl.flock(fd, fcntl.LOCK_UN)
            except OSError:
                pass
            os.close(fd)


def reconcile_stale_ownership() -> str:
    """Convenience cold-start reconciliation using default gate configuration.

    Returns ``CLEAN`` when no stale record exists or a stale ``running``
    record was verified against its persisted baseline (owned adapter gone,
    owned drift zero after restoration) and cleared.  Returns
    ``RECOVERY_UNVERIFIED`` when verification or restoration failed so the
    durable record stays on disk and blocks future starts.
    """
    return TunRecoveryGate().reconcile_stale_ownership()
