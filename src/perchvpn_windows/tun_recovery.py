"""Fail-closed recovery gate for the Windows TUN sidecar.

The gate writes an ownership record *before* the sidecar is spawned, then
records the child PID and process creation time.  On the next start (or after
the child exits) it verifies that no adapter with the expected identity
survives.  Anything that cannot be proven clean is reported as
``RECOVERY_UNVERIFIED``.

The gate never terminates a process by PID and never deletes an adapter.
"""

